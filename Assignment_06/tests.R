Sys.setenv(BDA400_TEST_MODE='1')
source('app.R')
results<-data.frame(Test=character(),Passed=logical())
check<-function(name,value) {ok<-isTRUE(value);results[nrow(results)+1,]<<-list(name,ok);cat(if(ok)'PASS' else 'FAIL',name,'\n')}
eq<-function(a,b)isTRUE(all.equal(a,b,check.attributes=FALSE,tolerance=1e-9))
err<-function(expr)inherits(tryCatch({force(expr);NULL},error=function(e)e),'error')
z<-fetch_stock('AAPL','2024-01-02','2024-03-28','Saved Yahoo snapshot')
d<-z$data
check('Saved Yahoo schema and row count',nrow(d)==61 && identical(names(d),c('Date','Open','High','Low','Close','Volume')))
check('MA known example',eq(rolling_mean(c(1,2,3,4),2),c(NA,1.5,2.5,3.5)))
check('MA insufficient history',all(is.na(rolling_mean(1:3,5))))
check('EMA known recurrence',eq(ema_price(c(10,12,14),3),c(10,11,12.5)))
check('Wilder RSI correct seed',eq(wilder_rsi(c(45,50,48,55,52,49,58),5)[6],60))
check('RSI flat convention',eq(tail(wilder_rsi(rep(1,20),5),1),50))
check('True crossovers not daily states',identical(cross_events(c(0,2,3,2,0),rep(1,5)),c('Hold','Buy','Hold','Hold','Sell')))
check('Equality crossing boundary',identical(cross_events(c(1,2,1,0),rep(1,4)),c('Hold','Buy','Hold','Sell')))
check('Missing warmup creates no event',identical(cross_events(c(NA,2,3),rep(1,3)),rep('Hold',3)))
check('Mismatched crossing input rejected',err(cross_events(1:2,1:3)))
x<-calculate_indicators(d)
check('Date alignment',nrow(x)==61 && sum(is.na(x$SlowMA))==19 && sum(is.na(x$RSI))==14)
check('Final bar cannot execute next open',is.na(tail(x$NextOpen,1)) && is.na(tail(x$NextBarDate,1)))
check('Next-bar open is forward shifted',eq(x$NextOpen[-61],x$Open[-1]))
check('Invalid MA periods rejected',err(calculate_indicators(d,20,5)))
check('Noninteger period rejected',err(calculate_indicators(d,5.5,20)))
w<-aggregate_frame(d,'Weekly');m<-aggregate_frame(d,'Monthly')
check('Weekly/monthly bar counts',nrow(w)==13 && nrow(m)==3)
check('Weekly volume conserved',sum(w$Volume)==sum(d$Volume))
check('Monthly OHLC aggregation',eq(m$Open[1],d$Open[1]) && eq(m$High[1],max(d$High[format(d$Date,'%m')=='01'])))
check('Reversed date range rejected',err(fetch_stock('AAPL','2024-03-28','2024-01-02','Saved Yahoo snapshot')))
check('Missing symbol cache rejected',err(fetch_stock('ZZZZZZ','2024-01-02','2024-03-28','Saved Yahoo snapshot')))
check('Unsupported cached dates rejected',err(fetch_stock('AAPL','2025-01-01','2025-02-01','Saved Yahoo snapshot')))
check('Invalid OHLC rejected',err({bad<-d;bad$Low[1]<-bad$High[1]+1;validate_ohlcv(bad)}))
# No lookahead: adding later daily prices cannot change earlier indicators/signals.
short<-calculate_indicators(d[1:40,])
check('Causal signal prefix',identical(x$Signal[1:40],short$Signal) && eq(x$RSI[1:40],short$RSI) && eq(x$MACD[1:40],short$MACD))
for(chart in c('Candlestick','Line','Area')) {
  p<-make_chart(x,chart,c('Moving Averages','RSI','MACD'),TRUE)
  check(paste('Render',chart),!err(ggplot_build(p)))
}
for(ind in list(character(), 'Moving Averages','RSI','MACD')) {
  p<-make_chart(x,'Line',ind,FALSE)
  layout<-ggplot_build(p)$layout$layout
  check(paste('Toggle panels',paste(ind,collapse=',')),nrow(layout)==1+sum(c('RSI','MACD')%in%ind))
}
