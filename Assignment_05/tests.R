# Validation references (stats::lm / sd) are tests, never implementations.
source('load_all.R')
results <- data.frame(Test=character(),Passed=logical())
check <- function(name, value) {
  ok <- isTRUE(value); results[nrow(results)+1,] <<- list(name,ok)
  cat(if(ok) 'PASS' else 'FAIL',name,'\n')
}
eq <- function(a,b) isTRUE(all.equal(a,b,tolerance=1e-10,check.attributes=FALSE))
err <- function(expr) inherits(tryCatch({force(expr);NULL},error=function(e)e),'error')
x <- c(10,12,15,20,18,22,25,24,21)
check('SMA supplied example',eq(sma(x,3),c(37,47,53,60,65,71,70)/3))
check('SMA period one',eq(sma(x,1),x))
check('SMA entire window',eq(sma(x,9),sum(x)/9))
check('SMA short input error',err(sma(x,10)))
check('SMA missing-window propagation',eq(sma(c(1,NA_real_,3,4),2),c(NA,NA,3.5)))
check('EMA known recurrence',eq(ema(c(10,12,14),3),c(10,11,12.5)))
check('EMA period one',eq(ema(x,1),x))
check('EMA empty vector',eq(ema(numeric(),3),numeric()))
check('EMA period exceeds n',eq(ema(c(1,2),5),c(1,4/3)))
m <- macd(c(1,2,3),1,3,2)
check('MACD independently known values',eq(m$macd_line,c(0,.5,.75)) && eq(m$signal_line,c(0,1/3,11/18)) && eq(m$histogram,c(0,1/6,5/36)))
check('MACD exact return names',identical(names(m),c('macd_line','signal_line','histogram')))
check('MACD constant zero',eq(macd(rep(7,20),3,5,2)$histogram,rep(0,20)))
check('Population SD known',eq(stdev(c(2,4,6)),sqrt(8/3)))
check('Population vs sample reference',eq(stdev(x),sd(x)*sqrt((length(x)-1)/length(x))))
check('SD single and constant',stdev(3)==0 && stdev(rep(3,5))==0)
check('SD empty input error',err(stdev(numeric())))
l <- linreg(2+3*(1:10),4,0)
check('Regression coefficients',eq(l$slope,3) && eq(l$intercept,17))
check('Literal regression window has L+1 points',length(l$predicted_values)==5)
y <- c(3,7,4,8,2,9,11,10,8,14)
l <- linreg(y,6,1); selected <- y[5:9]; ix <- seq_along(selected)
fit <- lm(selected~ix)
check('Regression independent lm reference',eq(l$slope,unname(coef(fit)[2])) && eq(l$intercept,unname(coef(fit)[1])) && eq(l$predicted_values,unname(fitted(fit))))
check('Regression invalid length',err(linreg(y,11,0)))
check('Regression invalid offset',err(linreg(y,6,6)))
check('Regression reversed indices rejected',err(linreg(y,6,5)))
check('Regression singleton rejected',err(linreg(1,1,0)))
r <- c(45,50,48,55,52,49,58,60,65,62)
# First p=5 changes: gains12/5=2.4 losses8/5=1.6.
# Literal update repeats fifth change (-3): gain1.92 loss1.88.
check('RSI literal seed-update convention',eq(rsi(r,5)[6],100*1.92/3.8))
check('RSI Wilder correct initial seed',eq(rsi_wilder(r,5)[6],60))
check('RSI up-only',eq(tail(rsi(1:20,5),1),100))
check('RSI down-only',eq(tail(rsi(20:1,5),1),0))
check('RSI flat convention',eq(tail(rsi(rep(10,20),5),1),50))
check('RSI insufficient changes',all(is.na(rsi(1:5,5))))
check('RSI warmup length',all(is.na(rsi(r,5)[1:5])) && !is.na(rsi(r,5)[6]))
s <- stoch_rsi(r,14,3,3)
check('Supplied short StochRSI example stays NA',length(s$k_line)==8 && length(s$d_line)==6 && all(is.na(s$k_line)) && all(is.na(s$d_line)))
z <- cumsum(c(10,rep(c(3,-2,5,-4,1,-1,2),10)))
s <- stoch_rsi(z,5,3,3)
rr <- rsi(z,5); raw <- (rr-min(rr,na.rm=TRUE))/(max(rr,na.rm=TRUE)-min(rr,na.rm=TRUE))
check('StochRSI global normalization reference',eq(s$k_line,sma(raw,3)) && eq(s$d_line,sma(s$k_line,3)))
check('StochRSI compact lengths',length(s$k_line)==length(z)-2 && length(s$d_line)==length(z)-4)
check('StochRSI bounds',all(s$k_line[!is.na(s$k_line)]>=0 & s$k_line[!is.na(s$k_line)]<=1))
check('StochRSI flat range remains undefined',all(is.na(stoch_rsi(rep(1,30),5,3,3)$d_line)))
a <- c(0,1,2,1,0,2); b <- rep(1,6)
check('Crossover literal strings and equality',identical(crossover(a,b),c('None','None','Up','None','Down','Up')))
check('Crossunder literal strings',identical(crossunder(a,b),c('None','False','False','False','True','False')))
check('Logical crossover adapter',identical(crossover_logical(a,b),c(FALSE,FALSE,TRUE,FALSE,FALSE,TRUE)))
check('Cross missing comparisons no event',identical(crossover(c(NA_real_,2,0),rep(1,3)),c('None','None','Down')))
check('Cross empty vectors',length(crossover(numeric(),numeric()))==0)
check('Cross mismatched lengths rejected',err(crossunder(1:3,1:2)))
for (p in list(0,-1,1.5,NA_real_,Inf,'3')) check(paste('Invalid period',p),err(sma(x,p)))
for (f in list(sma,ema,rsi)) check(paste('Nonnumeric rejected',deparse(substitute(f))),err(f(c('a','b'),1)))
check('Infinite values rejected',err(ema(c(1,Inf),2)))
check('Missing prices rejected by RSI',err(rsi(c(1,NA_real_,2),1)))
# Prefix invariance: causal outputs cannot change when future prices are appended.
check('EMA causal prefix',eq(ema(z,5)[1:30],ema(z[1:30],5)))
check('Wilder RSI causal prefix',eq(rsi_wilder(z,5)[1:30],rsi_wilder(z[1:30],5)))
check('Rolling StochRSI causal prefix',eq(stoch_rsi_rolling(z,5,3,3)$d_line[1:30],stoch_rsi_rolling(z[1:30],5,3,3)$d_line))
# Add an extreme declining future to demonstrate the supplied global-normalization leak.
z2 <- c(z[1:30],seq(z[30]-10,z[30]-300,by=-10))
check('Global StochRSI future dependence demonstrated',!eq(stoch_rsi(z2,5,3,3)$k_line[1:28],stoch_rsi(z[1:30],5,3,3)$k_line))
args <- list(sma=list(x,3),ema=list(x,3),macd=list(x,3,5,2),stdev=list(x),
             linreg=list(x,5,0),rsi=list(x,3),stoch_rsi=list(z,5,3,3),
             crossover=list(x,x),crossunder=list(x,x))
for (name in names(args)) {
  e <- new.env(parent=baseenv()); sys.source(file.path('indicators',paste0(name,'.R')),envir=e)
  check(paste('Standalone script',name),!err(do.call(e[[name]],args[[name]])))
}
write.csv(results,'evidence/test_results.csv',row.names=FALSE)
cat('\nSummary:',sum(results$Passed),'/',nrow(results),'passed\n')
if (!all(results$Passed)) stop('Test failures')
