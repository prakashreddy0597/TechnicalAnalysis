 check('Shiny reactive daily selection',nrow(visible())==61)
 session$setInputs(symbol='MSFT',chart='Area')
 check('Shiny stock switch',eq(tail(visible()$Close,1),420.720001220703))
 session$setInputs(frame='Weekly')
 check('Shiny timeframe switch',nrow(visible())==13)
 session$setInputs(frame='Daily',dates=as.Date(c('2024-03-01','2024-03-28')))
 check('Visible date filter preserves earlier warmup',all(visible()$Date>=as.Date('2024-03-01')) && !is.na(visible()$SlowMA[1]))
 session$setInputs(strategy='MACD crossover + RSI gate')
 check('Shiny custom strategy',all(visible()$Signal%in%c('Buy','Sell','Hold')))
 session$setInputs(fast=30,slow=20)
 check('Shiny invalid periods handled',err(visible()))
})
